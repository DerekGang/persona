/**
 * #13282: the same native About host as #13076, now in a real emulator window. Only instrumentation supplies the
 * generated Build slot. There is no production selection, and no TalkBack claim: these are Compose semantics and
 * real-window captures, not speech from an enabled accessibility service. Screenshots stay in test-app storage.
 */
@RunWith(AndroidJUnit4::class)
class AboutBuildHostInstrumentedTest {
    @get:Rule val rule = createAndroidComposeRule<ComponentActivity>()
    private val instrumentation get() = InstrumentationRegistry.getInstrumentation()
    private val context: Context get() = instrumentation.targetContext

    @Test fun realPackageInfoSupportsHandwrittenGeneratedHandwrittenRollback() {
        val info = context.packageManager.getPackageInfo(context.packageName, 0)
        val build = info.longVersionCode.toString()
        val snapshot = AboutBuildSnapshot.from(info)
        assertEquals(build, snapshot.buildNumber)
        val commit = BuildCommit.parse("0123456789abcdef0123456789abcdef01234567")
        var generated by mutableStateOf(false)
        var dark by mutableStateOf(false)
        val notices = mutableListOf<String>()
        val feedback = object : AppFeedback {
            override fun failure(error: Throwable, operation: Boolean) = false
            override fun notice(message: String): Boolean { notices += message; return true }
        }
        rule.setContent {
            PersonaTheme(darkTheme = dark, reduceMotion = true) {
                Box {
                    JToastHost(rememberToastState())
                    CompositionLocalProvider(LocalAppFeedback provides feedback) {
                        Column {
                            AboutSettingsPage(commit, buildRow = if (generated) {
                                { AboutBuildRow(snapshot.buildNumber, Modifier.testTag("generated-build")) }
                            } else {
                                null
                            })
                        }
                    }
                }
            }
        }
        assertHost(build, native = true)
        capture("handwritten-light", "English light; handwritten default from the real test package")

        generated = true
        rule.waitForIdle()
        assertHost(build, native = false)
        capture("generated-light", "English light; the same real package value through the generated Build slot")
        assertEquals("Switching only the test Build slot must not copy", emptyList<String>(), notices)
        rule.onAllNodes(nativeBuildRow(build)).assertCountEquals(1).onFirst().performClick()
        rule.onNodeWithTag("generated-build", useUnmergedTree = true).performClick()
        rule.waitForIdle()
        assertEquals("Read-only Build clicks must not copy", emptyList<String>(), notices)

        rule.waitForIdle()
        instrumentation.runOnMainSync { rule.activity.window.decorView.requestFocus() }
        val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
        val copied = AtomicReference<String?>(null)
        val latch = CountDownLatch(1)
        val listener = ClipboardManager.OnPrimaryClipChangedListener {
            copied.set(clipboard.primaryClip?.getItemAt(0)?.coerceToText(context)?.toString())
            latch.countDown()
        }
        instrumentation.runOnMainSync { clipboard.addPrimaryClipChangedListener(listener) }
        try {
            rule.onNodeWithText("Commit").assertHasClickAction().performClick()
            rule.waitForIdle()
            assertTrue("Native Commit click must reach the system clipboard listener",
                latch.await(60, TimeUnit.SECONDS))
            assertEquals(listOf("Build commit copied"), notices)
            assertEquals(commit!!.full, copied.get())
            assertTrue(rule.activity.isFinishing.not())
        } finally {
            instrumentation.runOnMainSync { clipboard.removePrimaryClipChangedListener(listener) }
        }
        capture("generated-commit-click-light", "Native Commit click; full-value copy and localized confirmation")

        dark = true
        rule.waitForIdle()
        capture("generated-dark", "English dark; unchanged generated Build slot and native siblings")

        generated = false
        rule.waitForIdle()
        assertHost(build, native = true)
        capture("handwritten-rollback-dark", "English dark; restored handwritten default")
    }

    @Test fun localizedGeneratedAndHandwrittenRowsAreReadOnlyWithReal48dpBounds() {
        var language by mutableStateOf(localeContext("en"))
        var dark by mutableStateOf(false)
        var generated by mutableStateOf(false)
        rule.setContent {
            CompositionLocalProvider(LocalContext provides language, LocalResources provides language.resources) {
                PersonaTheme(darkTheme = dark, reduceMotion = true) {
                    Column {
                        AboutSettingsPage(commit = null, buildRow = if (generated) {
                            { AboutBuildRow(null, Modifier.testTag("generated-build")) }
                        } else {
                            null
                        })
                    }
                }
            }
        }
        val realBuild = context.packageManager.getPackageInfo(context.packageName, 0).longVersionCode.toString()
        for ((tag, title, fallback) in listOf(
            Triple("en", "Build", "Not provided"),
            Triple("zh-CN", "构建号", "未提供"),
            Triple("ja", "ビルド番号", "情報なし"),
        )) {
            rule.runOnIdle { language = localeContext(tag) }
            for (useGenerated in listOf(false, true)) {
                rule.runOnIdle { generated = useGenerated }
                rule.waitForIdle()
                val row = if (useGenerated) {
                    rule.onNodeWithTag("generated-build", useUnmergedTree = true)
                } else {
                    rule.onAllNodes(nativeBuildRow(realBuild)).assertCountEquals(1).onFirst()
                }
                row.assertIsDisplayed().assertHasNoClickAction()
                row.assertMinimumTouchTarget("$tag generated=$useGenerated")
                val semantics = row.readRowSemantics()
                if (useGenerated) {
                    assertEquals("$tag generated title/fallback", listOf(title, fallback), semantics.text)
                } else {
                    assertEquals("$tag handwritten real Build", listOf(title, realBuild), semantics.text)
                }
                assertTrue("$tag read-only descriptions", semantics.descriptions.isEmpty())
                assertTrue("$tag read-only click labels", semantics.clickLabels.isEmpty())
                assertTrue("$tag read-only custom actions", semantics.customActions.isEmpty())
                if (useGenerated) {
                    assertRealClickLeavesBuildUnchanged()
                    capture("$tag-generated-fallback", "$tag localized generated optional-input fallback; no TalkBack enabled")
                }
            }
        }
    }

    private fun assertHost(build: String, native: Boolean) {
        rule.onAllNodesWithText("Build").assertCountEquals(1)
        rule.onNodeWithText(build, useUnmergedTree = true).assertIsDisplayed()
        val title = if (native) {
            rule.onAllNodes(nativeBuildRow(build)).assertCountEquals(1).onFirst()
        } else {
            rule.onNodeWithTag("generated-build", useUnmergedTree = true)
        }
        title.assertHasNoClickAction()
        title.assertMinimumTouchTarget(if (native) "handwritten" else "generated")
        if (!native) {
            val semantics = title.readRowSemantics()
            assertEquals(listOf("Build", build), semantics.text)
            assertTrue(semantics.clickLabels.isEmpty())
            assertTrue(semantics.customActions.isEmpty())
        }
        if (native) {
            rule.onNodeWithTag("generated-build", useUnmergedTree = true).assertDoesNotExist()
        } else {
            rule.onNodeWithTag("generated-build", useUnmergedTree = true).assertIsDisplayed()
        }
        rule.onNodeWithText("Commit").assertIsDisplayed()
    }

    private fun nativeBuildRow(value: String) =
        hasAnyChild(hasText("Build", substring = false)) and
            hasAnyChild(hasText(value, substring = false))

    private fun assertRealClickLeavesBuildUnchanged() {
        val before = clipboardText()
        val row = rule.onNodeWithTag("generated-build", useUnmergedTree = true)
        row.performClick()
        rule.waitForIdle()
        rule.onNodeWithTag("generated-build", useUnmergedTree = true).assertIsDisplayed()
        assertEquals("Read-only Build must not change the clipboard", before, clipboardText())
        assertFalse(rule.activity.isFinishing)
    }

    private fun clipboardText(): String? {
        var text: String? = null
        instrumentation.runOnMainSync {
            val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
            text = clipboard.primaryClip?.takeIf {
                it.description.hasMimeType(ClipDescription.MIMETYPE_TEXT_PLAIN) && it.itemCount > 0
            }?.getItemAt(0)?.coerceToText(context)?.toString()
        }
        return text
    }

    private fun localeContext(tag: String): Context = context.createConfigurationContext(
        Configuration(context.resources.configuration).apply { setLocale(Locale.forLanguageTag(tag)) })

    private fun capture(name: String, meaning: String) {
        rule.waitForIdle()
        instrumentation.waitForIdleSync()
        val folder = File(context.getExternalFilesDir(null), "about-build-host").apply { mkdirs() }
        val bitmap = requireNotNull(instrumentation.uiAutomation.takeScreenshot()) { "no real-window screenshot" }
        File(folder, "$name.png").outputStream().use { bitmap.compress(Bitmap.CompressFormat.PNG, 100, it) }
        val enabled = android.provider.Settings.Secure.getString(
            context.contentResolver, android.provider.Settings.Secure.ENABLED_ACCESSIBILITY_SERVICES)
        File(folder, "$name.json").writeText(
            """{"name":"$name","kind":"emulator","physicalDevice":false,"model":"${Build.MODEL}","androidRelease":"${Build.VERSION.RELEASE}","sdk":${Build.VERSION.SDK_INT},"buildId":"${Build.ID}","displayId":"${Build.DISPLAY}","buildType":"${Build.TYPE}","testPackage":"${context.packageName}","testVersionCode":${context.packageManager.getPackageInfo(context.packageName, 0).longVersionCode},"testBuildType":"debug","density":${context.resources.displayMetrics.density},"accessibilityServices":${jsonString(enabled)},"talkBackVerified":false,"pid":${Process.myPid()},"meaning":${jsonString(meaning)}}""")
        instrumentation.uiAutomation.executeShellCommand(
            "dumpsys package ${context.packageName}").use { descriptor ->
            android.os.ParcelFileDescriptor.AutoCloseInputStream(descriptor).use {
                File(folder, "package.txt").writeText(it.reader().readText())
            }
        }
    }

    private fun jsonString(value: String?): String = value?.let {
        "\"" + it.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
    } ?: "null"

    private fun SemanticsNodeInteraction.assertMinimumTouchTarget(label: String) {
        val node = fetchSemanticsNode()
        val minimum = with(rule.density) { Tokens.MinTouch.android.toPx() }
        assertTrue("$label width ${node.touchBoundsInRoot.width} below $minimum", node.touchBoundsInRoot.width >= minimum)
        assertTrue("$label height ${node.touchBoundsInRoot.height} below $minimum", node.touchBoundsInRoot.height >= minimum)
        assertTrue("$label must be visible on the real target", node.boundsInRoot.height > 0)
    }

    private fun SemanticsNodeInteraction.readRowSemantics(): RowSemantics = fetchSemanticsNode().readRowSemantics()

    private fun SemanticsNode.readRowSemantics(): RowSemantics {
        val descendants = descendants()
        return RowSemantics(
            text = descendants.flatMap { it.config.getOrNull(SemanticsProperties.Text).orEmpty() }.map { it.text },
            descriptions = descendants.flatMap { it.config.getOrNull(SemanticsProperties.ContentDescription).orEmpty() },
            clickLabels = descendants.mapNotNull { it.config.clickAction() }.map { it.label },
            customActions = descendants.mapNotNull { it.config.getOrNull(SemanticsActions.CustomActions) }
                .map { actions -> actions.map { action -> action.label } },
        )
    }

    private fun SemanticsConfiguration.clickAction(): AccessibilityAction<() -> Boolean>? =
        if (contains(SemanticsActions.OnClick)) this[SemanticsActions.OnClick] else null

    private fun SemanticsNode.descendants(): List<SemanticsNode> = listOf(this) + children.flatMap { it.descendants() }

    private data class RowSemantics(
        val text: List<String>,
        val descriptions: List<String>,
        val clickLabels: List<String?>,
        val customActions: List<List<String>>,
    )
}
